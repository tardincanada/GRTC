"""Block and item compositions from data/compositions.csv, with rarity correction from data/rarity.csv.

Units: 1 block = 1000 units, so an item that crafts 9-to-a-block is 111.1 units, a nugget 12.35 units,
and a bucket 1000 units. Each row gives the item's total units ('amount') and its makeup as
';'-separated 'ref:percent' entries. A ref is a substance id, an element id, or 'block:<id>' /
'item:<id>' to reuse another row's makeup. Rows whose id starts with '#' are comments.

Rarity correction: the game makes some elements (gold, copper, ...) far more common than they
really are. For each element in rarity.csv,

    factor = min(1, (real abundance relative to iron / in-game abundance relative to iron) ** RARITY_EXPONENT)

and every part containing that element yields only `factor` of its units. Pure refined metal (ingots,
nuggets, metal blocks) is not corrected again. A substance takes the
factor of its scarcest corrected element. The units removed become GANGUE, the miners' word for the
worthless rock around an ore; separating gangue gives the composition of REMAINDER (ordinary stone).
The total always stays equal to the item's amount. The exponent compresses the real ratio, which spans
up to seven orders of magnitude, into something playable: 1 would be fully realistic, 0 turns it off.
"""
import csv
import json
from pathlib import Path

RARITY_EXPONENT = 0.25
REFERENCE_PPM = 56300  # iron in Earth's crust
REMAINDER = "minecraft:stone"
GANGUE = "gangue"
# Machine-made mixtures (residues, alloys) are already won from their ores: no rarity correction.
REFINED = {"periodic_elements:anode_slime", "periodic_elements:radon_seed", "periodic_elements:pitchblende_residue",
           "periodic_elements:zinc_flue_dust", "periodic_elements:chamber_sludge", "periodic_elements:bittern"}
# Floors on the rarity factor, for elements the game needs more of than the formula gives. Mercury: redstone
# would be 3.4% cinnabar (34 redstone per mercury); Guilherme asked for 10% (about 12 per mercury).
FACTOR_FLOOR = {"mercury": 0.10}


def load_rarity(path, elements):
    ids = {e["id"] for e in elements}
    factors = {}
    with Path(path).open(newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            el = r["element"].strip()
            assert el in ids, f"rarity.csv: unknown element {el}"
            real = float(r["crust_ppm"]) / REFERENCE_PPM
            game = float(r["game_vs_iron"])
            factors[el] = min(1.0, max(FACTOR_FLOOR.get(el, 0.0), (real / game) ** RARITY_EXPONENT))
    return factors


def generate_compositions(csv_path, rarity_path, elements, substances, runtime_dir, extra_rows=(), fallback_rows=()):
    element_ids = {e["id"] for e in elements}
    symbol_to_id = {e["symbol"]: e["id"] for e in elements}
    substance_by_id = {s["id"]: s for s in substances}
    known = element_ids | set(substance_by_id)

    raw = {}
    with Path(csv_path).open(newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            key = row["id"].strip()
            if not key or key.startswith("#"):
                continue
            assert key not in raw, f"duplicate id {key}"
            parts = []
            for item in row["composition"].split(";"):
                ref, pct = item.strip().rsplit(":", 1)
                parts.append((ref, float(pct)))
            total = sum(p for _, p in parts)
            assert abs(total - 100) < 0.51, f"{key} sums to {total}%"
            raw[key] = (float(row["amount"]), parts)
    # Rows generated by other tools (trees.py): (id, amount, composition).
    for key, amount, comp in extra_rows:
        assert key not in raw, f"duplicate id {key}"
        parts = [(ref.strip(), float(pct)) for ref, pct in (item.strip().rsplit(":", 1) for item in comp.split(";"))]
        assert abs(sum(p for _, p in parts) - 100) < 0.51, f"{key} sums to {sum(p for _, p in parts)}%"
        raw[key] = (float(amount), parts)

    # Rows derived from vanilla recipes (crafted.py): only for ids no other row gives.
    for key, amount, comp in fallback_rows:
        if key in raw:
            continue
        parts = [(ref.strip(), float(pct)) for ref, pct in (item.strip().rsplit(":", 1) for item in comp.split(";"))]
        assert abs(sum(p for _, p in parts) - 100) < 0.51, f"{key} sums to {sum(p for _, p in parts)}%"
        raw[key] = (float(amount), parts)

    # Every element and substance item is 111.1 units of itself, so machines accept it as input or reagent.
    implicit = set()
    for ident in sorted(known):
        key = f"periodic_elements:{ident}"
        if key not in raw:
            raw[key] = (1000.0 / 9.0, [(ident, 100.0)])
            implicit.add(key)

    shares = {}

    def resolve(key, trail=()):
        """Fractions (summing to 1) of each substance or element in `key`, before rarity correction."""
        if key in shares:
            return shares[key]
        assert key in raw, f"unknown reference {key}"
        assert key not in trail, f"cycle: {' -> '.join(trail + (key,))}"
        _, parts = raw[key]
        total = sum(p for _, p in parts)
        out = {}
        for ref, pct in parts:
            w = pct / total
            if ref.startswith(("block:", "item:")):
                for k, v in resolve(ref.split(":", 1)[1], trail + (key,)).items():
                    out[k] = out.get(k, 0) + v * w
            else:
                assert ref in known, f"{key}: unknown substance or element {ref!r}"
                out[ref] = out.get(ref, 0) + w
        shares[key] = out
        return out

    factors = load_rarity(rarity_path, elements)

    def factor_of(part):
        if part in element_ids:
            return factors.get(part, 1.0)
        comp = substance_by_id[part]["composition"]
        return min([factors.get(symbol_to_id[sym], 1.0) for sym in comp] + [1.0])

    result = {}
    for key, (amount, _) in raw.items():
        units = {}
        lost = 0.0
        shares_of_key = resolve(key)
        # A pure element (an ingot, nugget or metal block) is already refined: the rarity correction was
        # applied when it was won from its ore, so it keeps all of its units.
        refined = (len(shares_of_key) == 1 and next(iter(shares_of_key)) in element_ids) or key in implicit or key in REFINED
        for part, frac in shares_of_key.items():
            f = 1.0 if refined else factor_of(part)
            units[part] = units.get(part, 0) + amount * frac * f
            lost += amount * frac * (1 - f)
        if lost > 1e-9:
            units[GANGUE] = lost
        assert abs(sum(units.values()) - amount) < 1e-6 * max(1, amount)
        result[key] = {
            "amount": amount,
            "parts": [{"id": k, "units": round(v, 3) if v >= 1e-3 else float(f"{v:.3g}")} for k, v in sorted(units.items(), key=lambda kv: -kv[1])],
        }
    (runtime_dir / "compositions.json").write_text(json.dumps(result, indent=1) + "\n", encoding="utf-8")
    old = runtime_dir / "block_compositions.json"
    if old.exists():
        old.unlink()
    return result, factors
