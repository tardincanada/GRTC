package com.periodicelements;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import net.minecraft.block.Block;
import net.minecraft.item.ArmorItem;
import net.minecraft.item.ArmorMaterial;
import net.minecraft.item.AxeItem;
import net.minecraft.item.HoeItem;
import net.minecraft.item.Item;
import net.minecraft.item.MiningToolItem;
import net.minecraft.item.PickaxeItem;
import net.minecraft.item.ShovelItem;
import net.minecraft.item.SwordItem;
import net.minecraft.item.ToolMaterial;
import net.minecraft.recipe.Ingredient;
import net.minecraft.registry.Registries;
import net.minecraft.registry.Registry;
import net.minecraft.registry.RegistryKeys;
import net.minecraft.registry.entry.RegistryEntry;
import net.minecraft.registry.tag.TagKey;
import net.minecraft.sound.SoundEvents;
import net.minecraft.util.Identifier;

import java.util.EnumMap;
import java.util.List;

/**
 * Tools, armor and weapons from process-gated materials, from {@code gear.json} (generated by tools/gear.py).
 * Each material is made from an alloy only one machine produces, so the gear follows the research tree.
 */
public final class Gear {
	public static Item HAND_CANNON;

	private Gear() {
	}

	private static Identifier id(String path) {
		return Identifier.of(PeriodicElements.MOD_ID, path);
	}

	private record Material(int durability, float speed, float damage, int enchantability, TagKey<Block> incorrect,
							String repair) implements ToolMaterial {
		@Override
		public int getDurability() {
			return durability;
		}

		@Override
		public float getMiningSpeedMultiplier() {
			return speed;
		}

		@Override
		public float getAttackDamage() {
			return damage;
		}

		@Override
		public TagKey<Block> getInverseTag() {
			return incorrect;
		}

		@Override
		public int getEnchantability() {
			return enchantability;
		}

		@Override
		public Ingredient getRepairIngredient() {
			return Ingredient.ofItems(Registries.ITEM.get(Identifier.of(repair)));
		}
	}

	static void register(List<Item> items) {
		JsonObject root = ElementTable.readObject("/periodic_elements/gear.json");
		for (JsonElement e : root.getAsJsonArray("materials")) {
			JsonObject m = e.getAsJsonObject();
			String mid = m.get("id").getAsString();
			String repair = m.get("ingot").getAsString();
			Material tool = new Material(m.get("durability").getAsInt(), m.get("speed").getAsFloat(),
					m.get("damage").getAsFloat(), m.get("enchantability").getAsInt(),
					TagKey.of(RegistryKeys.BLOCK, Identifier.of(m.get("incorrect").getAsString())), repair);
			RegistryEntry<ArmorMaterial> armorMaterial = m.has("armor") ? armorMaterial(mid, m, repair) : null;
			int mult = m.has("armor") ? m.get("durabilityMultiplier").getAsInt() : 0;
			double armorSpeed = m.has("armorSpeed") ? m.get("armorSpeed").getAsDouble() : 0;
			for (JsonElement ie : m.getAsJsonArray("items")) {
				JsonObject o = ie.getAsJsonObject();
				String kind = o.get("kind").getAsString();
				Item.Settings s = new Item.Settings();
				Item item = switch (kind) {
					case "sword" -> new SwordItem(tool, s.attributeModifiers(SwordItem.createAttributeModifiers(tool,
							(int) o.get("base").getAsFloat(), o.get("speed").getAsFloat())));
					case "pickaxe" -> new PickaxeItem(tool, s.attributeModifiers(MiningToolItem.createAttributeModifiers(
							tool, o.get("base").getAsFloat(), o.get("speed").getAsFloat())));
					case "axe" -> new AxeItem(tool, s.attributeModifiers(MiningToolItem.createAttributeModifiers(
							tool, o.get("base").getAsFloat(), o.get("speed").getAsFloat())));
					case "shovel" -> new ShovelItem(tool, s.attributeModifiers(MiningToolItem.createAttributeModifiers(
							tool, o.get("base").getAsFloat(), o.get("speed").getAsFloat())));
					case "hoe" -> new HoeItem(tool, s.attributeModifiers(MiningToolItem.createAttributeModifiers(
							tool, o.get("base").getAsFloat(), o.get("speed").getAsFloat())));
					case "sledgehammer", "excavator" -> new com.periodicelements.mining.AreaToolItem(tool, kind.equals("sledgehammer"),
							s.attributeModifiers(com.periodicelements.mining.AreaToolItem.modifiers(tool, o.get("base").getAsFloat(),
									o.get("speed").getAsFloat())));
					case "helmet" -> armor(armorMaterial, ArmorItem.Type.HELMET, mult, armorSpeed);
					case "chestplate" -> armor(armorMaterial, ArmorItem.Type.CHESTPLATE, mult, armorSpeed);
					case "leggings" -> armor(armorMaterial, ArmorItem.Type.LEGGINGS, mult, armorSpeed);
					case "boots" -> armor(armorMaterial, ArmorItem.Type.BOOTS, mult, armorSpeed);
					default -> throw new IllegalStateException("unknown gear kind " + kind);
				};
				items.add(Registry.register(Registries.ITEM, id(o.get("id").getAsString()), item));
			}
		}
		registerGuns(root, items);
	}

	private static RegistryEntry<ArmorMaterial> armorMaterial(String mid, JsonObject m, String repair) {
		{
			var armor = m.getAsJsonArray("armor");
			EnumMap<ArmorItem.Type, Integer> defense = new EnumMap<>(ArmorItem.Type.class);
			defense.put(ArmorItem.Type.BOOTS, armor.get(0).getAsInt());
			defense.put(ArmorItem.Type.LEGGINGS, armor.get(1).getAsInt());
			defense.put(ArmorItem.Type.CHESTPLATE, armor.get(2).getAsInt());
			defense.put(ArmorItem.Type.HELMET, armor.get(3).getAsInt());
			defense.put(ArmorItem.Type.BODY, armor.get(2).getAsInt());
			RegistryEntry<ArmorMaterial> armorMaterial = Registry.registerReference(Registries.ARMOR_MATERIAL, id(mid),
					new ArmorMaterial(defense, m.get("armorEnchantability").getAsInt(), SoundEvents.ITEM_ARMOR_EQUIP_IRON,
							() -> Ingredient.ofItems(Registries.ITEM.get(Identifier.of(repair))),
							List.of(new ArmorMaterial.Layer(id(mid))), m.get("toughness").getAsFloat(),
							m.get("knockback").getAsFloat()));
			return armorMaterial;
		}
	}

	private static void registerGuns(JsonObject root, List<Item> items) {
		for (JsonElement ge : root.getAsJsonArray("guns")) {
			JsonObject g = ge.getAsJsonObject();
			Item gun = Registry.register(Registries.ITEM, id(g.get("id").getAsString()), new HandCannonItem(
					new Item.Settings().maxDamage(g.get("durability").getAsInt()), g));
			if (g.get("id").getAsString().equals("hand_cannon")) {
				HAND_CANNON = gun;
			}
			items.add(gun);
		}
	}

	private static Item armor(RegistryEntry<ArmorMaterial> material, ArmorItem.Type type, int mult, double speed) {
		Item.Settings settings = new Item.Settings().maxDamage(type.getMaxDamage(mult));
		if (speed <= 0) {
			return new ArmorItem(material, type, settings);
		}
		return new ArmorItem(material, type, settings) {
			private net.minecraft.component.type.AttributeModifiersComponent withSpeed;

			@Override
			public net.minecraft.component.type.AttributeModifiersComponent getAttributeModifiers() {
				if (withSpeed == null) {
					var slot = net.minecraft.component.type.AttributeModifierSlot.forEquipmentSlot(type.getEquipmentSlot());
					withSpeed = super.getAttributeModifiers().with(
							net.minecraft.entity.attribute.EntityAttributes.GENERIC_MOVEMENT_SPEED,
							new net.minecraft.entity.attribute.EntityAttributeModifier(
									id("light_armor_" + type.getName()), speed,
									net.minecraft.entity.attribute.EntityAttributeModifier.Operation.ADD_MULTIPLIED_BASE),
							slot);
				}
				return withSpeed;
			}
		};
	}
}
