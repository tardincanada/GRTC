package com.periodicelements;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import net.fabricmc.fabric.api.biome.v1.BiomeModifications;
import net.fabricmc.fabric.api.biome.v1.BiomeSelectionContext;
import net.fabricmc.fabric.api.biome.v1.BiomeSelectors;
import net.minecraft.block.AbstractBlock;
import net.minecraft.block.Block;
import net.minecraft.block.Blocks;
import net.minecraft.block.ExperienceDroppingBlock;
import net.minecraft.item.BlockItem;
import net.minecraft.item.Item;
import net.minecraft.item.ItemStack;
import net.minecraft.item.tooltip.TooltipType;
import net.minecraft.registry.Registries;
import net.minecraft.registry.Registry;
import net.minecraft.registry.RegistryKey;
import net.minecraft.registry.RegistryKeys;
import net.minecraft.registry.tag.TagKey;
import net.minecraft.text.Text;
import net.minecraft.util.Formatting;
import net.minecraft.util.Identifier;
import net.minecraft.util.math.intprovider.UniformIntProvider;
import net.minecraft.world.gen.GenerationStep;

import java.util.ArrayList;
import java.util.List;
import java.util.function.Predicate;

/**
 * The mod's ores and raw ore items, and their world generation, from {@code ores.json} (generated by
 * tools/ores.py). Vein shapes and heights are in data/periodic_elements/worldgen; this adds them to biomes.
 */
public final class OreContent {
	public static final List<Block> ORES = new ArrayList<>();

	private OreContent() {
	}

	private static Identifier id(String path) {
		return Identifier.of(PeriodicElements.MOD_ID, path);
	}

	private static AbstractBlock.Settings settings(String host) {
		return switch (host) {
			case "deepslate" -> AbstractBlock.Settings.copy(Blocks.DEEPSLATE_IRON_ORE);
			case "netherrack" -> AbstractBlock.Settings.copy(Blocks.NETHER_GOLD_ORE);
			case "sandstone" -> AbstractBlock.Settings.copy(Blocks.SANDSTONE).requiresTool();
			case "sand" -> AbstractBlock.Settings.copy(Blocks.SAND);
			default -> AbstractBlock.Settings.copy(Blocks.IRON_ORE);
		};
	}

	/** Registers ore blocks, their block items and the raw ore items, adding the items to {@code items}. */
	static void register(List<Item> items) {
		JsonObject root = ElementTable.readObject("/periodic_elements/ores.json");
		for (JsonElement e : root.getAsJsonArray("ores")) {
			JsonObject o = e.getAsJsonObject();
			String oid = o.get("id").getAsString();
			Block block = Registry.register(Registries.BLOCK, id(oid), new ExperienceDroppingBlock(
					UniformIntProvider.create(o.get("xpMin").getAsInt(), o.get("xpMax").getAsInt()),
					settings(o.get("host").getAsString())));
			ORES.add(block);
			items.add(Registry.register(Registries.ITEM, id(oid), new BlockItem(block, new Item.Settings()) {
				@Override
				public void appendTooltip(ItemStack stack, TooltipContext context, List<Text> tooltip, TooltipType type) {
					tooltip.add(Text.translatable(getBlock().getTranslationKey() + ".desc").formatted(Formatting.GRAY));
				}
			}));
		}
		for (JsonElement e : root.getAsJsonArray("rawItems")) {
			items.add(Registry.register(Registries.ITEM, id(e.getAsString()), new Item(new Item.Settings()) {
				@Override
				public void appendTooltip(ItemStack stack, TooltipContext context, List<Text> tooltip, TooltipType type) {
					tooltip.add(Text.translatable(getTranslationKey() + ".tip").formatted(Formatting.GRAY));
				}
			}));
		}

		for (JsonElement e : root.getAsJsonArray("features")) {
			JsonObject f = e.getAsJsonObject();
			RegistryKey<net.minecraft.world.gen.feature.PlacedFeature> key =
					RegistryKey.of(RegistryKeys.PLACED_FEATURE, id(f.get("id").getAsString()));
			BiomeModifications.addFeature(biomes(f.get("biomes").getAsString()),
					GenerationStep.Feature.UNDERGROUND_ORES, key);
		}
	}

	/** "overworld", "nether", "#tag" or a biome id, joined with "|". */
	static Predicate<BiomeSelectionContext> biomes(String spec) {
		Predicate<BiomeSelectionContext> out = null;
		for (String s : spec.split("\\|")) {
			Predicate<BiomeSelectionContext> p;
			if (s.equals("overworld")) {
				p = BiomeSelectors.foundInOverworld();
			} else if (s.equals("nether")) {
				p = BiomeSelectors.foundInTheNether();
			} else if (s.startsWith("#")) {
				p = BiomeSelectors.tag(TagKey.of(RegistryKeys.BIOME, Identifier.of(s.substring(1))));
			} else {
				p = BiomeSelectors.includeByKey(RegistryKey.of(RegistryKeys.BIOME, Identifier.of(s)));
			}
			out = out == null ? p : out.or(p);
		}
		return out;
	}
}
