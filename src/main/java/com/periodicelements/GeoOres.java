package com.periodicelements;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import net.minecraft.block.AbstractBlock;
import net.minecraft.block.Block;
import net.minecraft.block.BlockState;
import net.minecraft.block.Blocks;
import net.minecraft.block.ExperienceDroppingBlock;
import net.minecraft.item.BlockItem;
import net.minecraft.item.Item;
import net.minecraft.item.ItemStack;
import net.minecraft.item.tooltip.TooltipType;
import net.minecraft.registry.Registries;
import net.minecraft.registry.Registry;
import net.minecraft.text.Text;
import net.minecraft.util.Formatting;
import net.minecraft.util.Identifier;
import net.minecraft.util.math.intprovider.UniformIntProvider;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

/**
 * Ores in other host rocks (granite, basalt, sandstone...), used by the Geological world's deposits. Each one
 * drops what its stone ore drops. Generated by tools/geo_ores.py into {@code geo_ores.json}.
 */
public final class GeoOres {
	/** Every variant block, for the client's render layer. */
	public static final List<Block> VARIANTS = new ArrayList<>();
	/** host rock block -> mineral -> ore block in that rock (stone and deepslate map to the existing ores). */
	private static final Map<Block, Map<String, Block>> BY_ROCK = new HashMap<>();
	/** variant block -> id of the stone ore it stands for (so the Atlas counts both as one ore). */
	private static final Map<Block, Identifier> BASE = new HashMap<>();

	private GeoOres() {
	}

	static void register(List<Item> items) {
		JsonObject root = ElementTable.readObject("/periodic_elements/geo_ores.json");
		for (JsonElement e : root.getAsJsonArray("variants")) {
			JsonObject o = e.getAsJsonObject();
			Block rock = Registries.BLOCK.get(Identifier.of(o.get("rock").getAsString()));
			boolean soft = o.has("soft") && o.get("soft").getAsBoolean();
			AbstractBlock.Settings settings = soft
					? AbstractBlock.Settings.copy(rock).strength(0.9F) // placer gravel: dug with a shovel, no tier
					: AbstractBlock.Settings.copy(Blocks.IRON_ORE).mapColor(rock.getDefaultMapColor())
							.sounds(rock.getDefaultState().getSoundGroup());
			Identifier id = Identifier.of(PeriodicElements.MOD_ID, o.get("id").getAsString());
			Block block = Registry.register(Registries.BLOCK, id, new ExperienceDroppingBlock(
					UniformIntProvider.create(o.get("xpMin").getAsInt(), o.get("xpMax").getAsInt()), settings));
			VARIANTS.add(block);
			OreContent.ORES.add(block);
			BASE.put(block, Identifier.of(o.get("base").getAsString()));
			BY_ROCK.computeIfAbsent(rock, k -> new HashMap<>()).put(o.get("mineral").getAsString(), block);
			boolean desc = o.get("desc").getAsBoolean();
			items.add(Registry.register(Registries.ITEM, id, new BlockItem(block, new Item.Settings()) {
				@Override
				public void appendTooltip(ItemStack stack, TooltipContext context, List<Text> tooltip, TooltipType type) {
					if (desc) tooltip.add(Text.translatable(getBlock().getTranslationKey() + ".desc").formatted(Formatting.GRAY));
				}
			}));
		}
		// rocks that already have an ore of the mineral (stone, deepslate, sandstone for the crusts)
		JsonObject minerals = root.getAsJsonObject("minerals");
		for (String m : minerals.keySet()) {
			JsonObject hosts = minerals.getAsJsonObject(m);
			for (String host : hosts.keySet()) {
				BY_ROCK.computeIfAbsent(Registries.BLOCK.get(Identifier.of(host)), k -> new HashMap<>())
						.put(m, Registries.BLOCK.get(Identifier.of(hosts.get(host).getAsString())));
			}
		}
	}

	/** The ore of {@code mineral} in the rock {@code host} is, or null if there is none. */
	public static BlockState ore(String mineral, BlockState host) {
		Map<String, Block> m = BY_ROCK.get(host.getBlock());
		if (m == null) return null;
		Block b = m.get(mineral);
		return b == null ? null : b.getDefaultState();
	}

	/** True if deposits may replace this block (stone, deepslate or a rock with ore variants). */
	public static boolean host(BlockState s) {
		return BY_ROCK.containsKey(s.getBlock());
	}

	/** The stone ore a variant stands for, or null if the block is not a variant. */
	public static Identifier baseOf(Block b) {
		return BASE.get(b);
	}
}
