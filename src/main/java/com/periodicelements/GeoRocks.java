package com.periodicelements;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import net.minecraft.block.AbstractBlock;
import net.minecraft.block.Block;
import net.minecraft.block.MapColor;
import net.minecraft.block.SlabBlock;
import net.minecraft.block.StairsBlock;
import net.minecraft.block.WallBlock;
import net.minecraft.block.enums.NoteBlockInstrument;
import net.minecraft.item.BlockItem;
import net.minecraft.item.Item;
import net.minecraft.registry.Registries;
import net.minecraft.registry.Registry;
import net.minecraft.sound.BlockSoundGroup;
import net.minecraft.util.Identifier;

import java.util.List;

/**
 * The Geological world's own rocks (stage 4a, 3.42.0): shale, gneiss, peridotite, kimberlite and laterite, each with
 * cobbled and polished forms and polished stairs, slab and wall. Generated by tools/geo_rocks.py into
 * {@code geo_rocks.json}. Registered before {@link GeoOres}, whose ores in these rocks need them.
 */
public final class GeoRocks {
	public static Block SHALE, GNEISS, PERIDOTITE, KIMBERLITE, LATERITE;
	/** Soils by rock (4c): dug like dirt, tilled to farmland by a hoe. */
	public static Block TERRA_ROXA, CHALKY_SOIL;

	private GeoRocks() {
	}

	static void register(List<Item> items) {
		JsonObject root = ElementTable.readObject("/periodic_elements/geo_rocks.json");
		for (JsonElement e : root.getAsJsonArray("blocks")) {
			JsonObject o = e.getAsJsonObject();
			String form = o.get("form").getAsString();
			Identifier id = Identifier.of(PeriodicElements.MOD_ID, o.get("id").getAsString());
			MapColor color = mapColor(o.get("color").getAsString());
			AbstractBlock.Settings settings = AbstractBlock.Settings.create().mapColor(color)
					.instrument(NoteBlockInstrument.BASEDRUM).requiresTool()
					.strength(o.get("hardness").getAsFloat(), o.get("resistance").getAsFloat())
					.sounds(o.get("id").getAsString().contains("laterite") ? BlockSoundGroup.MUD_BRICKS : BlockSoundGroup.STONE);
			Block block = switch (form) {
				case "stairs" -> new StairsBlock(Registries.BLOCK.get(Identifier.of(o.get("base").getAsString())).getDefaultState(), settings);
				case "slab" -> new SlabBlock(settings);
				case "wall" -> new WallBlock(settings.solid());
				default -> new Block(settings);
			};
			Registry.register(Registries.BLOCK, id, block);
			items.add(Registry.register(Registries.ITEM, id, new BlockItem(block, new Item.Settings())));
			if (form.equals("rock")) {
				switch (id.getPath()) {
					case "shale" -> SHALE = block;
					case "gneiss" -> GNEISS = block;
					case "peridotite" -> PERIDOTITE = block;
					case "kimberlite" -> KIMBERLITE = block;
					case "laterite" -> LATERITE = block;
					default -> {
					}
				}
			}
		}
		for (JsonElement e : root.getAsJsonArray("soils")) {
			String sid = e.getAsString();
			Identifier id = Identifier.of(PeriodicElements.MOD_ID, sid);
			Block block = Registry.register(Registries.BLOCK, id, new Block(AbstractBlock.Settings.copy(net.minecraft.block.Blocks.DIRT)
					.mapColor(sid.equals("terra_roxa") ? MapColor.TERRACOTTA_RED : MapColor.PALE_YELLOW)));
			items.add(Registry.register(Registries.ITEM, id, new BlockItem(block, new Item.Settings())));
			net.fabricmc.fabric.api.registry.TillableBlockRegistry.register(block, net.minecraft.item.HoeItem::canTillFarmland,
					net.minecraft.block.Blocks.FARMLAND.getDefaultState());
			if (sid.equals("terra_roxa")) TERRA_ROXA = block;
			else CHALKY_SOIL = block;
		}
	}

	private static MapColor mapColor(String name) {
		return switch (name) {
			case "COLOR_GRAY" -> MapColor.GRAY;
			case "DARK_GREEN" -> MapColor.DARK_GREEN;
			case "TERRACOTTA_CYAN" -> MapColor.TERRACOTTA_CYAN;
			case "TERRACOTTA_RED" -> MapColor.TERRACOTTA_RED;
			default -> MapColor.STONE_GRAY;
		};
	}
}
